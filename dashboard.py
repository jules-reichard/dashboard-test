# --- Data Fetching ---
@st.cache_data
def load_data(ticker, period='5y'):
    """
    Downloads and caches historical stock data from Yahoo Finance.
    """
    try:
        data = yf.download(ticker, period=period, interval='1d')
        if data.empty:
            st.error(f"No data returned for ticker: {ticker}. It might be delisted or incorrect.")
            return pd.DataFrame()

        # --- NEW: Calculate Moving Averages ---
        data['SMA_50'] = data['Close'].rolling(window=50).mean()
        data['SMA_200'] = data['Close'].rolling(window=200).mean()
        # --- End of NEW ---

        return data
    except Exception as e:
        st.error(f"Error downloading data: {e}")
        return pd.DataFrame()

# We hard-code 'AAPL' to ensure we only get data for one stock
